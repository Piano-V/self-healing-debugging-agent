import os
from langchain_core.prompts import ChatPromptTemplate
from state import AgentState, CodePatch
from tools import run_pytest


def get_llm():
    """Initializes and returns the appropriate LLM based on environment variables.

    Attempts to use Google Gemini first, falls back to a local fine-tuned Ollama model
    if configured or if cloud keys are missing, and finally falls back to OpenAI.
    """
    # 1. Try to load ChatGoogleGenerativeAI if GEMINI_API_KEY is present
    if os.environ.get("GEMINI_API_KEY") and not os.environ.get("USE_LOCAL_FALLBACK"):
        try:
            from langchain_google_genai import ChatGoogleGenerativeAI

            model_name = os.environ.get("GEMINI_MODEL", "gemini-3.5-flash")
            print(f"[LLM Setup] Using Google Gemini model: {model_name}")
            return ChatGoogleGenerativeAI(
                model=model_name,
                temperature=0.0,
                max_retries=2,
            )
        except ImportError:
            pass

    # 2. Try to load ChatOllama if USE_LOCAL_FALLBACK is true or GEMINI/OPENAI keys are not set
    # Uses a fine-tuned local coder model like qwen2.5-coder:1.5b or deepseek-coder
    if os.environ.get("USE_LOCAL_FALLBACK") or (not os.environ.get("GEMINI_API_KEY") and not os.environ.get("OPENAI_API_KEY")):
        try:
            import urllib.request
            # Fast ping to verify Ollama background service is running
            urllib.request.urlopen("http://localhost:11434", timeout=1.0)

            from langchain_ollama import ChatOllama
            local_model = os.environ.get("LOCAL_MODEL", "qwen2.5-coder:1.5b")
            print(f"[LLM Setup] Ollama service active. Using Local Model: {local_model}")
            return ChatOllama(
                model=local_model,
                temperature=0.0,
            )
        except Exception as e:
            print(f"[LLM Setup] Local Ollama is inactive or not installed ({e}). Falling back...")
            pass

    # 3. Try to load ChatOpenAI if OPENAI_API_KEY is present
    if os.environ.get("OPENAI_API_KEY"):
        try:
            from langchain_openai import ChatOpenAI

            model_name = os.environ.get("OPENAI_MODEL", "gpt-4o-mini")
            print(f"[LLM Setup] Using OpenAI model: {model_name}")
            return ChatOpenAI(
                model=model_name,
                temperature=0.0,
                max_retries=2,
            )
        except ImportError:
            pass

    # Default fallback: Attempt Gemini import
    # This will fail with an API key error if env is missing, which is standard behavior
    from langchain_google_genai import ChatGoogleGenerativeAI

    model_name = os.environ.get("GEMINI_MODEL", "gemini-3.5-flash")
    print(f"[LLM Setup] Defaulting to Google Gemini model: {model_name}")
    return ChatGoogleGenerativeAI(
        model=model_name,
        temperature=0.0,
    )


def test_runner_node(state: AgentState) -> dict:
    """Executes pytest against the current code content.

    Updates the state with the pytest traceback and the current success/failed status.
    """
    print("\n[Node: test_runner_node] Executing unit tests...")

    # Run tests using the tool
    passed, logs = run_pytest(state["code_content"], state["test_suite_code"])

    # Determine status
    status = "success" if passed else "failed"
    print(f"[Node: test_runner_node] Test Result: {status.upper()}")

    return {
        "test_logs": logs,
        "status": status,
    }


def clean_code(code: str) -> str:
    """Strips markdown code fences (e.g., ```python ... ```) if generated by the LLM."""
    code = code.strip()
    if code.startswith("```"):
        lines = code.splitlines()
        # Remove the starting markdown code block line
        if lines[0].startswith("```"):
            lines = lines[1:]
        # Remove the ending markdown code block line
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        code = "\n".join(lines)
    return code.strip()


def programmer_agent_node(state: AgentState) -> dict:
    """Invokes the LLM to analyze pytest failure logs and rewrite/patch the code.

    Enforces Pydantic structured output typing to receive only the patch and reasoning.
    """
    current_iteration = state["iteration_count"]
    print(
        f"\n[Node: programmer_agent_node] Starting debugging iteration {current_iteration + 1}..."
    )

    # Initialize model and bind structured output
    llm = get_llm()
    structured_llm = llm.with_structured_output(CodePatch)

    # Define system instructions and context format
    prompt = ChatPromptTemplate.from_messages(
        [
            (
                "system",
                (
                    "You are a Senior AI Platform Architect and expert Python debugger.\n"
                    "Your task is to fix the code inside `target_code.py` so that it successfully passes "
                    "all pytest unit tests.\n\n"
                    "Analyze the target code and the pytest failure traceback carefully. Identify the root cause "
                    "of the bugs (syntax errors, logical errors, edge cases, off-by-one errors) and repair it.\n\n"
                    "CRITICAL REQUIREMENTS:\n"
                    "1. Respond exactly matching the schema. You must provide a clear 'explanation' and the full, complete 'patched_code'.\n"
                    "2. The 'patched_code' must be the complete file content. Do NOT use markdown code blocks or backticks. Return raw python code."
                ),
            ),
            (
                "user",
                (
                    "--- TARGET CODE (target_code.py) ---\n"
                    "{code_content}\n\n"
                    "--- TEST FAILURE LOGS ---\n"
                    "{test_logs}\n"
                ),
            ),
        ]
    )

    chain = prompt | structured_llm

    try:
        response: CodePatch = chain.invoke(
            {
                "code_content": state["code_content"],
                "test_logs": state["test_logs"],
            }
        )

        print("\n--- PROGRAMMER REASONING ---")
        print(response.explanation)
        print("----------------------------")
        print("Generated code patch successfully.")

        # Clean the output code to strip any markdown backticks
        cleaned_code = clean_code(response.patched_code)

        # Return updated code and increment iteration count
        return {
            "code_content": cleaned_code,
            "iteration_count": current_iteration + 1,
        }

    except Exception as e:
        error_msg = f"Programmer agent failed to generate structured fix: {str(e)}"
        print(f"[Node: programmer_agent_node] Error: {error_msg}")

        # In case of LLM exception, pass through the traceback and increment iteration to prevent lockup
        return {
            "test_logs": (
                state["test_logs"]
                + f"\n\n[Agent Error in Iteration {current_iteration + 1}]: {error_msg}"
            ),
            "iteration_count": current_iteration + 1,
        }
